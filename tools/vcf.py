#!/usr/bin/env python3
"""Build the "More contacts" vCards from connect/contacts.json.

  python3 tools/vcf.py

Writes
  connect/vcf/<slug>.vcf             one card per department ("Vivint – <Department>", ORG Vivint)
  connect/vcf/vivint-sales-contacts.vcf   one consolidated card holding every number and email, labelled by department
and refreshes the data block in connect/contacts.js (between the DATA markers) so the sheet works offline and can
fall back to an in-page Blob when the static file can't be opened (claude.ai artifact copy, offline without cache).

contacts.json: "call" = call-only numbers, "text" = text-only numbers, "email" = addresses. Edit that file, then rerun.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'connect', 'contacts.json')
OUT = os.path.join(ROOT, 'connect', 'vcf')
JS = os.path.join(ROOT, 'connect', 'contacts.js')
ALL = 'vivint-sales-contacts'


def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower().replace('&', 'and')).strip('-')


def digits(p):
    d = re.sub(r'\D', '', p)
    return d[1:] if len(d) == 11 and d[0] == '1' else d


def e164(p):
    return '+1' + digits(p)


def esc(s):  # vCard 3.0 text escaping
    return s.replace('\\', '\\\\').replace(',', '\\,').replace(';', '\\;').replace('\n', '\\n')


def fold(line):  # RFC 6350/2426 folding at 75 octets, never splitting a UTF-8 sequence
    b = line.encode('utf-8')
    if len(b) <= 75:
        return line
    out, cur = [], b''
    for ch in line:
        e = ch.encode('utf-8')
        if len(cur) + len(e) > (75 if not out else 74):
            out.append(cur.decode('utf-8')); cur = b''
        cur += e
    out.append(cur.decode('utf-8'))
    return '\r\n '.join(out)


def card(name, org, entries):
    """entries: list of (kind, value, label) with kind in tel/email."""
    L = ['BEGIN:VCARD', 'VERSION:3.0', 'PRODID:-//Smart Home Pros//Contacts//EN',
         'N:%s;;;;' % esc(name), 'FN:%s' % esc(name), 'ORG:%s' % esc(org)]
    for i, (kind, val, label) in enumerate(entries, 1):
        if kind == 'tel':
            L.append('item%d.TEL;type=%s:%s' % (i, 'CELL' if 'text' in label.lower() else 'VOICE', e164(val)))
        else:
            L.append('item%d.EMAIL;type=INTERNET;type=WORK:%s' % (i, val))
        L.append('item%d.X-ABLabel:%s' % (i, esc(label)))
    L.append('END:VCARD')
    return '\r\n'.join(fold(l) for l in L) + '\r\n'


def main():
    data = json.load(open(SRC, encoding='utf-8'))['contacts']
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.vcf'):
            os.remove(os.path.join(OUT, f))
    rows, vcf, every = [], {}, []
    for c in data:
        n, s = c['name'], slug(c['name'])
        call, text, mail = c.get('call', []), c.get('text', []), c.get('email', [])
        own = [('tel', p, 'Call') for p in call] + [('tel', p, 'Text only') for p in text] + [('email', m, 'Email') for m in mail]
        vcf[s] = card('Vivint – ' + n, 'Vivint', own)
        every += [('tel', p, n) for p in call] + [('tel', p, n + ' (text only)') for p in text] + [('email', m, n) for m in mail]
        row = {'n': n, 'f': s, 'c': [digits(p) for p in call], 't': [digits(p) for p in text], 'e': mail}
        if c.get('star'):
            row['s'] = 1
        rows.append(row)
    vcf[ALL] = card('Vivint Sales Contacts', 'Vivint', every)
    for s, t in vcf.items():
        with open(os.path.join(OUT, s + '.vcf'), 'w', encoding='utf-8', newline='') as fh:
            fh.write(t)
    block = ('/* DATA:start (generated by tools/vcf.py from connect/contacts.json; do not hand-edit) */\n'
             'var DEPTS = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n'
             'var VCF = ' + json.dumps(vcf, ensure_ascii=False, separators=(',', ':')) + ';\n'
             '/* DATA:end */')
    js = open(JS, encoding='utf-8').read()
    new, k = re.subn(r'/\* DATA:start.*?/\* DATA:end \*/', lambda m: block, js, flags=re.S)
    if k != 1:
        raise SystemExit('DATA markers not found in connect/contacts.js')
    with open(JS, 'w', encoding='utf-8') as fh:
        fh.write(new)
    print('%d department cards + %s.vcf (%d entries) -> connect/vcf/; data refreshed in connect/contacts.js' % (len(data), ALL, len(every)))


if __name__ == '__main__':
    main()
